-- 1. TABELA EMPRESA
CREATE TABLE EMPRESA (
    ID SERIAL NOT NULL,
    EMP_ID SERIAL NOT NULL,
    EMP_NOME VARCHAR(120) NOT NULL,
    EMP_CNPJ_CPF VARCHAR(18),
    DT_LIBERADO DATE,
    DT_CAD TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_EMPRESA PRIMARY KEY (ID),
    CONSTRAINT UQ_EMPRESA_EMP_ID UNIQUE (EMP_ID)
);

-- 2. TABELA USUARIO
CREATE TABLE USUARIO (
    ID SERIAL NOT NULL,
    EMP_ID INT NOT NULL,
    USER_COD SERIAL NOT NULL,
    USER_NOME VARCHAR(120) NOT NULL,
    USER_TOKEN VARCHAR(200),
    USER_FIREBASE_UID VARCHAR(128),
    DT_CAD TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UQ_USUARIO_USER_COD UNIQUE (USER_COD),
    CONSTRAINT FK_USUARIO_EMPRESA FOREIGN KEY (EMP_ID) REFERENCES EMPRESA (EMP_ID)
);

-- 3. TABELA FUNCAO
CREATE TABLE FUNCAO (
    ID SERIAL NOT NULL,
    EMP_ID INT NOT NULL,
    FUNC_COD SERIAL NOT NULL,
    FUNC_DESC VARCHAR(200) NOT NULL,
    CONSTRAINT PK_FUNCAO PRIMARY KEY (ID),
    CONSTRAINT UQ_FUNCAO_FUNC_COD UNIQUE (FUNC_COD),
    CONSTRAINT FK_FUNCAO_EMPRESA FOREIGN KEY (EMP_ID) REFERENCES EMPRESA (EMP_ID)
);

-- 4. TABELA FUNC_USER
CREATE TABLE FUNC_USER (
    ID SERIAL NOT NULL,
    EMP_ID INT NOT NULL,
    FUNC_COD INT NOT NULL,
    USER_COD INT NOT NULL,
    COD_USER_FUNC SERIAL NOT NULL,
    CONSTRAINT PK_FUNC_USER PRIMARY KEY (ID),
    CONSTRAINT UQ_FUNC_USER_COD UNIQUE (COD_USER_FUNC),
    CONSTRAINT FK_FUNC_USER_EMPRESA FOREIGN KEY (EMP_ID) REFERENCES EMPRESA (EMP_ID),
    CONSTRAINT FK_FUNC_USER_FUNCAO FOREIGN KEY (FUNC_COD) REFERENCES FUNCAO (FUNC_COD),
    CONSTRAINT FK_FUNC_USER_USUARIO FOREIGN KEY (USER_COD) REFERENCES USUARIO (USER_COD)
);

-- 5. TABELA ESCALA
CREATE TABLE ESCALA (
    ID SERIAL NOT NULL,
    EMP_ID INT NOT NULL,
    ESC_COD SERIAL NOT NULL,
    ESC_DATA DATE NOT NULL,
    ESC_PERIODO CHAR(1),
    DT_CAD TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_ESCALA PRIMARY KEY (ID),
    CONSTRAINT UQ_ESCALA_ESC_COD UNIQUE (ESC_COD),
    CONSTRAINT FK_ESCALA_EMPRESA FOREIGN KEY (EMP_ID) REFERENCES EMPRESA (EMP_ID)
);

-- 6. TABELA ESC_ITEM
CREATE TABLE ESC_ITEM (
    ID SERIAL NOT NULL,
    ESC_COD INT NOT NULL,
    ESC_USER_FUNC INT NOT NULL,
    CONSTRAINT PK_ESC_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_ESC_ITEM_ESCALA FOREIGN KEY (ESC_COD) REFERENCES ESCALA (ESC_COD),
    CONSTRAINT FK_ESC_ITEM_FUNC_USER FOREIGN KEY (ESC_USER_FUNC) REFERENCES FUNC_USER (COD_USER_FUNC)
);

-- 7. TABELA INDISPO_USER
CREATE TABLE INDISPO_USER (
    ID SERIAL NOT NULL,
    EMP_ID INT NOT NULL,
    USER_COD INT NOT NULL,
    DT_INDISPO DATE NOT NULL,
    PERIODO CHAR(1),
    DT_CAD TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_INDISPO_USER PRIMARY KEY (ID),
    CONSTRAINT FK_INDISPO_USER_EMPRESA FOREIGN KEY (EMP_ID) REFERENCES EMPRESA (EMP_ID),
    CONSTRAINT FK_INDISPO_USER_USUARIO FOREIGN KEY (USER_COD) REFERENCES USUARIO (USER_COD)
);

-- 8. TABELA LOG
CREATE TABLE LOG (
    ID SERIAL NOT NULL,
    EMP_ID INT NOT NULL,
    USER_COD INT,
    LOG_ALT VARCHAR(600),
    DT_ALT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    TABELA_ALT VARCHAR(80),
    CONSTRAINT PK_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_LOG_EMPRESA FOREIGN KEY (EMP_ID) REFERENCES EMPRESA (EMP_ID),
    CONSTRAINT FK_LOG_USUARIO FOREIGN KEY (USER_COD) REFERENCES USUARIO (USER_COD)
);

-- 9. TABELA AVISOS
CREATE TABLE AVISOS (
    ID SERIAL NOT NULL,
    EMP_ID INT NOT NULL,
    AVISO_TEXT VARCHAR(200) NOT NULL,
    DT_AVISO TIMESTAMP NOT NULL,
    DT_CAD TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_AVISOS PRIMARY KEY (ID),
    CONSTRAINT FK_AVISOS_EMPRESA FOREIGN KEY (EMP_ID) REFERENCES EMPRESA (EMP_ID)
);

